begin;
create extension if not exists pgtap with schema extensions;
select plan(1);
do $$
declare
  staff uuid:=gen_random_uuid(); outsider uuid:=gen_random_uuid(); uid uuid; email text;
  invite jsonb; other_invite jsonb; expired_invite jsonb; blocked_invite jsonb; result jsonb;
  before_customers bigint; before_passes bigint; before_finance bigint; customer uuid; rejected boolean;
begin
  foreach uid in array array[staff,outsider] loop
    email:='qa-registration-'||uid||'@tests.invalid';
    insert into auth.users(id,email,raw_app_meta_data,raw_user_meta_data) values(uid,email,'{"provider":"email","providers":["email"]}','{}');
    insert into public.profiles(id,email,full_name,role,permissions,active) values(uid,email,'QA Registration','bar',case when uid=staff then '["bar.orders"]'::jsonb else '["bar.finance"]'::jsonb end,true)
      on conflict(id) do update set role='bar',permissions=excluded.permissions,active=true;
    insert into public.app_clients(id,full_name,email) values(uid,'QA Registration',email) on conflict(id) do nothing;
    insert into public.protected_access_accounts(email,full_name,role,permissions,active) values(email,'QA Registration','bar',case when uid=staff then '["bar.orders"]'::jsonb else '["bar.finance"]'::jsonb end,true);
  end loop;
  delete from day_use_private.public_registration_settings;
  select count(*) into before_customers from public.bar_day_use_customers;
  select count(*) into before_passes from public.bar_day_use_passes;
  select count(*) into before_finance from public.bar_financial_entries;
  perform set_config('request.jwt.claims',jsonb_build_object('sub',outsider,'role','authenticated','user_metadata',jsonb_build_object('role','admin'))::text,true);
  perform set_config('role','authenticated',true);
  rejected:=false;
  begin perform public.bar_create_day_use_invite(); exception when insufficient_privilege then rejected:=true; end;
  if not rejected then raise exception 'Read-only staff created invite'; end if;
  perform set_config('request.jwt.claims',jsonb_build_object('sub',staff,'role','authenticated')::text,true);
  perform public.bar_enable_day_use_public_registration();
  invite:=public.bar_create_day_use_invite();
  other_invite:=public.bar_create_day_use_invite();
  expired_invite:=public.bar_create_day_use_invite();
  blocked_invite:=public.bar_create_day_use_invite();
  if (invite->>'token') !~ '^[a-f0-9]{64}$' or (invite->>'expires_at')::timestamptz <> now()+interval '7 days' then raise exception 'Invalid capability'; end if;
  perform set_config('role','postgres',true);
  update day_use_private.bar_day_use_invites set expires_at=now()-interval '1 second' where token_hash=encode(extensions.digest(expired_invite->>'token','sha256'),'hex');
  perform set_config('request.jwt.claims','{"role":"anon"}',true);
  perform set_config('role','anon',true);
  rejected:=false;
  begin perform public.bar_create_day_use_invite(); exception when insufficient_privilege then rejected:=true; end;
  if not rejected then raise exception 'Anonymous minted invite'; end if;
  rejected:=false;
  begin perform * from public.bar_day_use_customers; exception when insufficient_privilege then rejected:=true; end;
  if not rejected then raise exception 'Anonymous read contacts'; end if;
  rejected:=false;
  begin perform * from day_use_private.bar_day_use_invites; exception when insufficient_privilege then rejected:=true; end;
  if not rejected then raise exception 'Anonymous read invite secrets'; end if;
  rejected:=false;
  begin perform public.bar_submit_day_use_registration(repeat('0',64),'QA Beach Pessoa','27999992222'); exception when others then if sqlerrm not like 'Link inválido%' then raise; end if; rejected:=true; end;
  if not rejected then raise exception 'Unknown token accepted'; end if;
  rejected:=false;
  begin perform public.bar_submit_day_use_registration(expired_invite->>'token','QA Beach Pessoa','27999992222'); exception when others then if sqlerrm not like 'Link inválido%' then raise; end if; rejected:=true; end;
  if not rejected then raise exception 'Expired token accepted'; end if;
  rejected:=false;
  begin perform public.bar_submit_day_use_registration(invite->>'token','Pessoa','27999992222'); exception when others then if sqlerrm not like 'Informe seu nome%' then raise; end if; rejected:=true; end;
  if not rejected then raise exception 'Incomplete name accepted'; end if;
  rejected:=false;
  begin perform public.bar_submit_day_use_registration(invite->>'token','QA Beach Pessoa','123'); exception when others then if sqlerrm not like 'Informe um telefone%' then raise; end if; rejected:=true; end;
  if not rejected then raise exception 'Invalid phone accepted'; end if;
  result:=public.bar_submit_day_use_registration(invite->>'token',' QA  Beach Pessoa ','(27) 99999-2222');
  if result<>'{"ok":true}'::jsonb then raise exception 'Response must not expose PII'; end if;
  result:=public.bar_submit_day_use_registration(invite->>'token','QA Beach Pessoa','5527999992222');
  if result<>'{"ok":true}'::jsonb then raise exception 'Lost response retry not idempotent'; end if;
  rejected:=false;
  begin perform public.bar_submit_day_use_registration(invite->>'token','QA Outra Pessoa','27999993333'); exception when others then if sqlerrm not like 'Este link já foi utilizado%' then raise; end if; rejected:=true; end;
  if not rejected then raise exception 'Used token overwritten'; end if;
  perform public.bar_submit_day_use_public_registration('QA Beach Pessoa','27999992222');
  -- A second invitation for the same contact must not create a duplicate.
  perform public.bar_submit_day_use_registration(other_invite->>'token','qa beach pessoa','27999992222');
  perform set_config('role','postgres',true);
  if (select count(*) from public.bar_day_use_customers)<>before_customers+1 then raise exception 'Contact duplicated'; end if;
  select id into strict customer from public.bar_day_use_customers where full_name='QA Beach Pessoa' and phone='5527999992222' and created_by=staff;
  if (select count(*) from public.bar_day_use_passes)<>before_passes or (select count(*) from public.bar_financial_entries)<>before_finance then raise exception 'Registration created financial activity'; end if;
  if (select count(*) from public.app_client_notifications where event_type='NOVO_CADASTRO_DAY_USE' and dedupe_key like 'day-use-registration:'||customer::text||':%')<>2 then raise exception 'Staff notifications missing or duplicated'; end if;
  if (select count(*) from day_use_private.bar_day_use_invites where customer_id=customer and used_at is not null)<>3 then raise exception 'Audit trail missing'; end if;
  update public.bar_day_use_customers set deleted_at=now(),delete_reason='QA removal' where id=customer;
  perform set_config('role','anon',true);
  perform public.bar_submit_day_use_registration(blocked_invite->>'token','QA Beach Pessoa','27999992222');
  perform set_config('role','postgres',true);
  if (select deleted_at from public.bar_day_use_customers where id=customer) is not null or (select count(*) from day_use_private.customer_reregistrations where customer_id=customer and previous_delete_reason='QA removal')<>1 then raise exception 'Re-registration did not preserve removal audit'; end if;
  if (select count(*) from public.bar_day_use_passes)<>before_passes or (select count(*) from public.bar_financial_entries)<>before_finance then raise exception 'Re-registration changed finances'; end if;
  perform set_config('request.jwt.claims',jsonb_build_object('sub',staff,'role','authenticated')::text,true);
  perform set_config('role','authenticated',true);
  for i in 6..30 loop perform public.bar_create_day_use_invite(); end loop;
  rejected:=false;
  begin perform public.bar_create_day_use_invite(); exception when others then if sqlerrm not like 'Limite de convites%' then raise; end if; rejected:=true; end;
  if not rejected then raise exception 'Invite rate limit bypassed'; end if;
  perform set_config('role','postgres',true);
end $$;
select pass('Individual Day Use registration: scoped invitations, no public PII, retries, duplicates, expiry and no financial writes');
select * from finish();
rollback;
